// Derive profile faces from the game renderer; do not maintain a second face design.
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('public/get-droned/assets/js/game.js', 'utf8');
const ast = ts.createSourceFile('game.js', source, ts.ScriptTarget.Latest, true);
const helpers = new Set(['hs', 'shade', 'camoFleck', 'rrect', 'outl', 'gearLine', 'gearBox']);
const declarations = [];
function visit(node) {
  if (ts.isFunctionDeclaration(node) && helpers.has(node.name?.text)) declarations.push(node.getText(ast));
  ts.forEachChild(node, visit);
}
visit(ast);
const kits = source.slice(source.indexOf('var PKITS=['), source.indexOf('var kitIdx=0'));
const headStart = source.indexOf('  var bodyKit=kit,bodyCol=col,bodyPAL=PAL;');
const headEnd = source.indexOf('\n  c.restore();\n\n  kit=bodyKit;', headStart);
if (headStart < 0 || headEnd < 0 || declarations.length !== helpers.size) throw Error('Game face renderer changed; update portrait extraction.');
const skin = source.match(/var SKIN='[^']+', SKIN2='[^']+';/)[0];
fs.writeFileSync('src/components/pilot-portrait.generated.js', `// Generated by scripts/generate-pilot-portraits.cjs from game.js. Do not edit.\n${skin}\nvar EMR=[];\n${kits}\n${declarations.join('\n')}\n
export function drawPortrait(canvas, selected) {
  var kit=selected.id==='god'?VEHICLE_SENTRY_KIT:PKITS.find(k=>k.id===selected.id);
  if(!kit)return;
  var c=canvas.getContext('2d');if(!c)return;
  var size=canvas.width, scale=size/25;
  c.clearRect(0,0,size,size);c.save();c.beginPath();c.arc(size/2,size/2,size/2-1,0,Math.PI*2);c.clip();
  c.fillStyle='#0f1828';c.fillRect(0,0,size,size);
  c.translate(size/2-1.2*scale,size/2+31*scale);c.scale(scale,scale);
  var col=kit.col,PAL=kit.pal,seed=selected.id==='god'?417:31;
  var rus=false,front=true,back=false,kind=null,mapKind='compound',unitSkin=SKIN;
  ${source.slice(headStart,headEnd)}
  c.restore();
}
`);
